// ---------- نرمال‌سازی فارسی ----------
function normalizePersian(text) {
    return String(text)
        .replace(/ي/g, 'ی').replace(/ك/g, 'ک').replace(/ة/g, 'ه').replace(/ۀ/g, 'ه')
        .replace(/[\u064B-\u065F\u0670]/g, '')
        .replace(/[\u200B\u200D\u200E\u200F\u202A-\u202E]/g, '')
        .replace(/\u200c/g, ' ')
        .replace(/[۰-۹]/g, d => '۰۱۲۳۴۵۶۷۸۹'.indexOf(d))
        .replace(/[٠-٩]/g, d => '٠١٢٣٤٥٦٧٨٩'.indexOf(d))
        .replace(/[.,:;؛،!?؟«»()\[\]{}"'\/\\@#$%^&*_+=|<>~`\-ـ]/g, ' ')
        .replace(/\s+/g, ' ')
        .trim()
        .toLowerCase();
}


// ---------- ریشه‌یاب فارسی ----------
function stemPersian(word) {
    let w = word;
    w = w.replace(/^(نمی|می)/, '');
    const sufs = ['هایی','های','ترین','تر','ها','اند','ایم','اید','است','یم','ید','ند','ام','ای'];
    for (const s of sufs) {
        if (w.length - s.length >= 3 && w.endsWith(s)) { w = w.slice(0, -s.length); break; }
    }
    return w.length >= 2 ? w : word;
}

// ---------- Levenshtein ----------
function levenshtein(a, b) {
    if (a === b) return 0;
    const la = a.length, lb = b.length;
    if (Math.abs(la - lb) > 2) return 3;
    const dp = [];
    for (let i = 0; i <= la; i++) dp[i] = [i];
    for (let j = 0; j <= lb; j++) dp[0][j] = j;
    for (let i = 1; i <= la; i++) {
        for (let j = 1; j <= lb; j++) {
            dp[i][j] = a[i-1] === b[j-1]
                ? dp[i-1][j-1]
                : 1 + Math.min(dp[i-1][j], dp[i][j-1], dp[i-1][j-1]);
        }
    }
    return dp[la][lb];
}

