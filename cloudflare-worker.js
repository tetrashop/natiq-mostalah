function scoreDomain(n, domain) {
    const expanded = expandWithSynonyms(n);
    const allTokens = expanded.split(' ');
    let score = 0;
    for (const kw of domain.keywords) {
        const nkw = normalizePersian(kw);
        if (nkw.length < 2) continue;
        let matched = false;
        if (nkw.length <= 3) {
            const idx = n.indexOf(nkw);
            if (idx >= 0) {
                const before = idx === 0 ? ' ' : n[idx - 1];
                if (before === ' ' || idx === 0) matched = true;
            }
        } else if (n.includes(nkw)) {
            matched = true;
        }
        if (matched) {
            const words = nkw.split(' ').length;
            score += Math.min(4, words + 1);
            continue;
        }
        for (const tok of allTokens) {
            if (tok.length < 2) continue;
            const m = matchWord(tok, nkw);
            if (m > 0) { score += m; break; }
        }
    }
    return score;
}

function analyzeQuestion(rawQuestion) {
    const n = normalizePersian(rawQuestion);
    const questionType = detectQuestionType(n);
    const scores = DOMAINS.map(d => ({ d, s: scoreDomain(n, d) })).sort((a, b) => b.s - a.s);
    const best = scores[0];
    const threshold = 2;

    if (best.s >= threshold) {
        const related = scores.slice(1, 4).filter(x => x.s > 0).map(x => x.d.name);
        return {
            matched: true,
            concept: best.d.name,
            depth: best.d.depth,
            response: best.d.response,
            confidence: Math.min(1, best.s / 6),
            questionType,
            relatedDomains: related,
            allScores: scores.slice(0, 5).map(x => ({ name: x.d.name, score: x.s }))
        };
    }

    const near = scores.slice(0, 3).filter(x => x.s > 0).map(x => x.d.name);
    return {
        matched: false,
        concept: 'خارج از دامنه تخصصی',
        depth: 1,
        response: buildFallback(n, near),
        confidence: 0,
        questionType,
        suggestedDomains: near.length > 0 ? near : DOMAINS.slice(0, 6).map(d => d.name),
        allScores: scores.slice(0, 5).map(x => ({ name: x.d.name, score: x.s }))
    };
}

