function detectQuestionType(n) {
    if (/(چیست|چیه|معنی|تعریف|یعنی چه|چی هست)/.test(n)) return 'definition';
    if (/(چطور|چگونه|راه های|روش|چجوری|چگونه میتوانم|چطور میتوانم)/.test(n)) return 'howto';
    if (/(چرا|دلیل|علت|باعث)/.test(n)) return 'why';
    if (/(بهترین|موثرترین|بهترین راه|اصولی ترین|کارامدترین)/.test(n)) return 'best';
    if (/(شروع|از کجا|اولین قدم|گام اول|بدو شروع)/.test(n)) return 'start';
    if (/(تفاوت|مقایسه|کدام بهتر|یا)/.test(n)) return 'compare';
    return 'general';
}

