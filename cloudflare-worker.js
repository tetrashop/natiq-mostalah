export default {
    async fetch(request, env, ctx) {
        const cors = {
            'Access-Control-Allow-Origin': '*',
            'Access-Control-Allow-Methods': 'GET, POST, OPTIONS',
            'Access-Control-Allow-Headers': 'Content-Type'
        };
        if (request.method === 'OPTIONS') return new Response(null, { headers: cors });
        const url = new URL(request.url);

        if (request.method === 'GET' && (url.pathname === '/' || url.pathname === '/dashboard')) {
            return new Response(getHomePage(), {
                headers: { 'Content-Type': 'text/html; charset=utf-8', ...cors }
            });
        }

        if (url.pathname === '/api/health') {
            return new Response(JSON.stringify({
                status: 'healthy',
                version: '5.1.0',
                domains_count: DOMAINS.length,
                domains: DOMAINS.map(d => d.name),
                timestamp: new Date().toISOString()
            }), { headers: { 'Content-Type': 'application/json; charset=utf-8', ...cors } });
        }

        if (url.pathname === '/api/domains') {
            return new Response(JSON.stringify({
                success: true,
                count: DOMAINS.length,
                domains: DOMAINS.map(d => ({ name: d.name, depth: d.depth, keywords_count: d.keywords.length }))
            }), { headers: { 'Content-Type': 'application/json; charset=utf-8', ...cors } });
        }

        if (url.pathname === '/api/analyze' && request.method === 'POST') {
            try {
                const body = await request.json();
                const question = body && body.question;
                if (!question) return new Response(JSON.stringify({ error: 'question required' }), { status: 400, headers: { 'Content-Type': 'application/json', ...cors } });
                const a = analyzeQuestion(question);
                return new Response(JSON.stringify({
                    success: true,
                    question,
                    normalized: normalizePersian(question),
                    analysis: {
                        primaryConcept: a.concept,
                        matched: a.matched,
                        confidence: a.confidence,
                        questionType: a.questionType,
                        allScores: a.allScores || [],
                        relatedDomains: a.relatedDomains || []
                    }
                }), { headers: { 'Content-Type': 'application/json; charset=utf-8', ...cors } });
            } catch (err) {
                return new Response(JSON.stringify({ success: false, error: err.message }), { status: 500, headers: { 'Content-Type': 'application/json', ...cors } });
            }
        }

        if (request.method === 'POST' && (url.pathname === '/' || url.pathname === '/api/ask')) {
            try {
                const body = await request.json();
                const question = body && body.question;
                if (!question || typeof question !== 'string' || question.trim().length < 2) {
                    return new Response(JSON.stringify({ success: false, error: 'سؤال معتبر ارائه نشده است (حداقل ۲ کاراکتر)' }), {
                        status: 400, headers: { 'Content-Type': 'application/json; charset=utf-8', ...cors }
                    });
                }
                if (question.length > 2000) {
                    return new Response(JSON.stringify({ success: false, error: 'سؤال طولانی‌تر از ۲۰۰۰ کاراکتر است' }), {
                        status: 400, headers: { 'Content-Type': 'application/json; charset=utf-8', ...cors }
                    });
                }
                const analysis = analyzeQuestion(question);
                return new Response(JSON.stringify({
                    success: true,
                    question,
                    response: analysis.response,
                    analysis: {
                        primaryConcept: analysis.concept,
                        depthLevel: analysis.depth,
                        matched: analysis.matched,
                        confidence: analysis.confidence,
                        questionType: analysis.questionType,
                        relatedDomains: analysis.relatedDomains || [],
                        suggestedDomains: analysis.suggestedDomains || []
                    },
                    metadata: {
                        version: '5.1.0',
                        timestamp: new Date().toISOString()
                    }
                }), { headers: { 'Content-Type': 'application/json; charset=utf-8', ...cors } });
            } catch (err) {
                return new Response(JSON.stringify({ success: false, error: 'خطا: ' + err.message }), {
                    status: 500, headers: { 'Content-Type': 'application/json; charset=utf-8', ...cors }
                });
            }
        }

        return new Response(JSON.stringify({ success: false, error: 'مسیر یافت نشد' }), {
            status: 404, headers: { 'Content-Type': 'application/json; charset=utf-8', ...cors }
        });
    }
};
